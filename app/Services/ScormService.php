<?php

namespace App\Services;

use App\Models\ScormModuleModel;
use CodeIgniter\Files\Exceptions\FileNotFoundException;
use CodeIgniter\HTTP\Files\UploadedFile;
use ZipArchive;

class ScormService
{
    private const MAX_FILE_SIZE     = 50 * 1024 * 1024; // 50 MB
    private const MAX_FILE_COUNT    = 2000;
    private const ALLOWED_EXTENSIONS = [
        'html',
        'htm',
        'js',
        'css',
        'xml',
        'xsd',
        'json',
        'txt',
        'png',
        'jpg',
        'jpeg',
        'gif',
        'svg',
        'webp',
        'pdf',
        'mp4',
        'webm',
        'ogg',
        'mp3',
        'wav',
        'woff',
        'woff2',
        'ttf',
        'eot',
    ];

    public function __construct(private readonly ScormModuleModel $model = new ScormModuleModel()) {}

    /**
     * Proses upload ZIP SCORM, ekstrak, dan simpan ke database.
     *
     * @return array{success: bool, message: string, module: array|null}
     */
    public function uploadAndExtract(UploadedFile $zipFile, ?UploadedFile $thumbnailFile, array $metadata): array
    {
        // 1. Validasi ZIP
        $validation = $this->validateZip($zipFile);
        if (! $validation['valid']) {
            return ['success' => false, 'message' => $validation['message'], 'module' => null];
        }

        // Move the upload into writable storage, then use the same importer as generated packages.
        $uuid = $this->generateUuid();
        $tempPath = WRITEPATH . 'uploads/' . $uuid . '.zip';
        $this->ensureDir(dirname($tempPath));

        try {
            $zipFile->move(dirname($tempPath), $uuid . '.zip', true);
        } catch (\Throwable $e) {
            return ['success' => false, 'message' => 'Gagal menyimpan file ZIP: ' . $e->getMessage(), 'module' => null];
        }

        return $this->importZipPath($tempPath, $thumbnailFile, $metadata, $uuid);
    }

    /**
     * Import a ZIP generated by DocumentToScormService.
     *
     * @return array{success: bool, message: string, module: array|null}
     */
    public function importGeneratedPackage(string $zipPath, ?UploadedFile $thumbnailFile, array $metadata): array
    {
        if (! is_file($zipPath)) {
            return ['success' => false, 'message' => 'Paket SCORM hasil konversi tidak ditemukan.', 'module' => null];
        }

        $uuid = $this->generateUuid();

        return $this->importZipPath($zipPath, $thumbnailFile, $metadata, $uuid);
    }

    /**
     * Extract and persist a validated or internally generated ZIP package.
     */
    private function importZipPath(string $tempPath, ?UploadedFile $thumbnailFile, array $metadata, string $uuid): array
    {
        // Extract to public/scorm/{uuid}/
        $extractPath = FCPATH . 'scorm/' . $uuid;
        $this->ensureDir($extractPath);

        $extractResult = $this->extractZip($tempPath, $extractPath);

        // 5. Hapus ZIP sementara
        @unlink($tempPath);

        if (! $extractResult['success']) {
            $this->rmdir($extractPath);

            return ['success' => false, 'message' => $extractResult['message'], 'module' => null];
        }

        // 6. Parse imsmanifest.xml
        $manifestPath = $extractPath . '/imsmanifest.xml';
        $manifest = $this->parseManifest($manifestPath);
        $launchFile = $manifest['launch_file'] ?? 'index.html';

        // 7. Validasi launch file ada
        if (! is_file($extractPath . '/' . $launchFile)) {
            $this->rmdir($extractPath);

            return ['success' => false, 'message' => 'File utama SCORM (' . $launchFile . ') tidak ditemukan setelah ekstraksi.', 'module' => null];
        }

        // 8. Proses thumbnail
        $thumbnailPath = '';
        if ($thumbnailFile !== null && $thumbnailFile->isValid() && ! $thumbnailFile->hasMoved() && str_starts_with($thumbnailFile->getMimeType(), 'image/')) {
            $thumbExt = $thumbnailFile->getExtension();
            $thumbName = $uuid . '_thumb.' . $thumbExt;
            $thumbDir = FCPATH . 'uploads/thumbnails';
            $this->ensureDir($thumbDir);

            try {
                $thumbnailFile->move($thumbDir, $thumbName, true);
                $thumbnailPath = 'uploads/thumbnails/' . $thumbName;
            } catch (\Throwable $e) {
                // Thumbnail optional, lanjutkan saja
            }
        }

        // 9. Simpan ke database
        $moduleId = $this->model->saveModule([
            'id'          => $uuid,
            'title'       => $metadata['title'] ?: $manifest['title'],
            'description' => $metadata['description'] ?: $manifest['description'],
            'folder_name' => $uuid,
            'launch_file' => $launchFile,
            'thumbnail'   => $thumbnailPath,
            'published'   => (int) ($metadata['published'] ?? 0),
            'created_by'  => (int) ($metadata['created_by'] ?? 0),
        ]);

        $module = $this->model->getModuleById($moduleId);

        return [
            'success' => true,
            'message' => 'Modul SCORM berhasil diunggah dan diekstrak.',
            'module'  => $module,
        ];
    }

    /**
     * Update metadata modul (tanpa upload ulang ZIP).
     *
     * @return array{success: bool, message: string}
     */
    public function updateModule(string $id, array $data, ?UploadedFile $thumbnailFile): array
    {
        $existing = $this->model->getModuleById($id);
        if ($existing === null) {
            return ['success' => false, 'message' => 'Modul tidak ditemukan.'];
        }

        $payload = [
            'title'       => trim((string) ($data['title'] ?? $existing['title'])),
            'description' => trim((string) ($data['description'] ?? $existing['description'] ?? '')),
            'published'   => (int) ($data['published'] ?? $existing['published'] ?? 0),
            'updated_at'  => date('Y-m-d H:i:s'),
        ];

        // Upload thumbnail baru jika ada
        if ($thumbnailFile !== null && $thumbnailFile->isValid() && ! $thumbnailFile->hasMoved() && str_starts_with($thumbnailFile->getMimeType(), 'image/')) {
            $thumbExt = $thumbnailFile->getExtension();
            $thumbName = $id . '_thumb.' . $thumbExt;
            $thumbDir = FCPATH . 'uploads/thumbnails';
            $this->ensureDir($thumbDir);

            try {
                // Hapus thumbnail lama
                if (! empty($existing['thumbnail'])) {
                    $oldThumb = FCPATH . $existing['thumbnail'];
                    if (is_file($oldThumb)) {
                        @unlink($oldThumb);
                    }
                }

                $thumbnailFile->move($thumbDir, $thumbName, true);
                $payload['thumbnail'] = 'uploads/thumbnails/' . $thumbName;
            } catch (\Throwable $e) {
                // Thumbnail optional
            }
        }

        $this->model->saveModule(array_merge($existing, $payload));

        return ['success' => true, 'message' => 'Modul berhasil diperbarui.'];
    }

    /**
     * Hapus modul dari database dan folder di disk.
     */
    public function deleteModule(string $id): bool
    {
        $module = $this->model->getModuleById($id);
        if ($module === null) {
            return false;
        }

        // Hapus folder ekstraksi
        if (! empty($module['folder_name'])) {
            $folderPath = FCPATH . 'scorm/' . $module['folder_name'];
            $this->rmdir($folderPath);
        }

        // Hapus thumbnail
        if (! empty($module['thumbnail'])) {
            $thumbPath = FCPATH . $module['thumbnail'];
            if (is_file($thumbPath)) {
                @unlink($thumbPath);
            }
        }

        // Hapus dari database
        return $this->model->deleteModule($id);
    }

    /**
     * Validasi file ZIP SCORM.
     */
    private function validateZip(UploadedFile $zipFile): array
    {
        // Cek ukuran
        if ($zipFile->getSize() > self::MAX_FILE_SIZE) {
            return ['valid' => false, 'message' => 'Ukuran file ZIP maksimal 50 MB.'];
        }

        // Cek ekstensi
        $extension = strtolower($zipFile->getExtension());
        if ($extension !== 'zip') {
            return ['valid' => false, 'message' => 'File harus berformat ZIP.'];
        }

        // Cek MIME
        $mime = $zipFile->getMimeType();
        $allowedMimes = ['application/zip', 'application/x-zip-compressed', 'application/octet-stream'];
        if (! in_array($mime, $allowedMimes, true)) {
            return ['valid' => false, 'message' => 'Tipe file ZIP tidak valid.'];
        }

        return ['valid' => true, 'message' => ''];
    }

    /**
     * Ekstrak ZIP dengan proteksi Zip Slip.
     */
    private function extractZip(string $zipPath, string $destination): array
    {
        $zip = new ZipArchive();
        $openResult = $zip->open($zipPath);

        if ($openResult !== true) {
            return ['success' => false, 'message' => 'Gagal membuka file ZIP (kode: ' . $openResult . ').'];
        }

        $fileCount = $zip->numFiles;
        if ($fileCount === 0) {
            $zip->close();

            return ['success' => false, 'message' => 'File ZIP kosong.'];
        }

        if ($fileCount > self::MAX_FILE_COUNT) {
            $zip->close();

            return ['success' => false, 'message' => 'Terlalu banyak file dalam ZIP (maksimal ' . self::MAX_FILE_COUNT . ' file).'];
        }

        $hasManifest = false;

        for ($i = 0; $i < $fileCount; $i++) {
            $filename = $zip->getNameIndex($i);
            if ($filename === false) {
                continue;
            }

            // Normalisasi path (gunakan forward slash)
            $filename = str_replace('\\', '/', $filename);

            // Proteksi Zip Slip: cek directory traversal
            if (str_contains($filename, '..') || str_starts_with($filename, '/')) {
                $zip->close();
                $this->rmdir($destination);

                return ['success' => false, 'message' => 'File ZIP mengandung path yang tidak aman (zip slip).'];
            }

            // Proteksi nama file berbahaya
            $basename = basename($filename);
            if ($basename === '' || $basename === '.' || $basename === '..') {
                continue;
            }

            // Cek ekstensi file
            if (! str_ends_with($filename, '/')) {
                $ext = strtolower(pathinfo($basename, PATHINFO_EXTENSION));
                if ($ext !== '' && ! in_array($ext, self::ALLOWED_EXTENSIONS, true)) {
                    $zip->close();
                    $this->rmdir($destination);

                    return ['success' => false, 'message' => 'Tipe file tidak diizinkan: .' . $ext];
                }
            }

            // Cek imsmanifest.xml di root
            if ($filename === 'imsmanifest.xml') {
                $hasManifest = true;
            }
        }

        if (! $hasManifest) {
            $zip->close();
            $this->rmdir($destination);

            return ['success' => false, 'message' => 'File imsmanifest.xml tidak ditemukan dalam ZIP.'];
        }

        // Ekstrak file
        for ($i = 0; $i < $fileCount; $i++) {
            $filename = $zip->getNameIndex($i);
            if ($filename === false) {
                continue;
            }

            $filename = str_replace('\\', '/', $filename);

            // Skip direktori
            if (str_ends_with($filename, '/')) {
                $dirPath = $destination . '/' . $filename;
                if (! is_dir($dirPath)) {
                    @mkdir($dirPath, 0755, true);
                }

                continue;
            }

            $destPath = $destination . '/' . $filename;
            $destDir = dirname($destPath);

            if (! is_dir($destDir)) {
                @mkdir($destDir, 0755, true);
            }

            // Baca konten file dan tulis
            $content = $zip->getFromIndex($i);
            if ($content === false) {
                continue;
            }

            if (file_put_contents($destPath, $content) === false) {
                $zip->close();
                $this->rmdir($destination);

                return ['success' => false, 'message' => 'Gagal menulis file: ' . $filename];
            }

            @chmod($destPath, 0644);
        }

        $zip->close();

        return ['success' => true, 'message' => ''];
    }

    /**
     * Parse imsmanifest.xml untuk metadata SCORM.
     */
    private function parseManifest(string $manifestPath): array
    {
        $result = [
            'title'       => '',
            'description' => '',
            'version'     => '',
            'launch_file' => 'index.html',
        ];

        if (! is_file($manifestPath)) {
            return $result;
        }

        // Matikan libxml errors untuk parsing yang tidak sempurna
        libxml_use_internal_errors(true);
        $xml = simplexml_load_file($manifestPath);
        if ($xml === false) {
            libxml_clear_errors();

            return $result;
        }

        // Register namespace SCORM
        $namespaces = $xml->getNamespaces(true);
        $ns = $namespaces[''] ?? ''; // Default namespace

        // Coba baca dari <organizations> atau <resources>
        // SCORM 1.2: <organizations><organization><title>
        // SCORM 2004: serupa
        if (isset($xml->organizations->organization)) {
            foreach ($xml->organizations->organization as $org) {
                if (isset($org->title)) {
                    $result['title'] = (string) $org->title;
                    break;
                }
            }
        }

        // Coba baca dari <metadata><schema><schemaversion>
        if (isset($xml->metadata->schemaversion)) {
            $result['version'] = (string) $xml->metadata->schemaversion;
        }

        // Cari launch file dari <resources>
        if (isset($xml->resources->resource)) {
            foreach ($xml->resources->resource as $resource) {
                $type = (string) $resource['type'];
                $href = (string) $resource['href'];

                if ($type === 'webcontent' && $href !== '') {
                    $result['launch_file'] = $href;
                    break;
                }

                // Fallback: resource pertama dengan href
                if ($href !== '' && $result['launch_file'] === '') {
                    $result['launch_file'] = $href;
                }
            }
        }

        // Fallback cari <manifest> identifier
        if ($result['title'] === '' && isset($xml['identifier'])) {
            $result['title'] = (string) $xml['identifier'];
        }

        // Deskripsi dari metadata
        if (isset($xml->metadata->description)) {
            $result['description'] = (string) $xml->metadata->description;
        }

        libxml_clear_errors();

        return $result;
    }

    /**
     * Toggle status publish modul.
     */
    public function togglePublished(string $id): array
    {
        $module = $this->model->getModuleById($id);
        if ($module === null) {
            return ['success' => false, 'message' => 'Modul tidak ditemukan.'];
        }

        $newStatus = ! empty($module['published']) ? 0 : 1;
        $this->model->togglePublished($id, $newStatus);

        $statusLabel = $newStatus ? 'diterbitkan' : 'ditarik';

        return ['success' => true, 'message' => 'Modul berhasil ' . $statusLabel . '.', 'published' => $newStatus];
    }

    /**
     * Generate UUID v4.
     */
    private function generateUuid(): string
    {
        $data = random_bytes(16);
        $data[6] = chr((ord($data[6]) & 0x0f) | 0x40);
        $data[8] = chr((ord($data[8]) & 0x3f) | 0x80);

        return vsprintf('%s%s-%s-%s-%s-%s%s%s', str_split(bin2hex($data), 4));
    }

    /**
     * Buat direktori jika belum ada.
     */
    private function ensureDir(string $path): void
    {
        if (! is_dir($path)) {
            @mkdir($path, 0755, true);
        }
    }

    /**
     * Hapus direktori beserta isinya secara rekursif.
     */
    private function rmdir(string $dir): void
    {
        if (! is_dir($dir)) {
            return;
        }

        $items = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($dir, \RecursiveDirectoryIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST
        );

        foreach ($items as $item) {
            if ($item->isDir()) {
                @rmdir($item->getRealPath());
            } else {
                @unlink($item->getRealPath());
            }
        }

        @rmdir($dir);
    }
}
